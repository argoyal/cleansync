import os
import re
from pathlib import Path

from sqlalchemy.orm import Session

from app.models import SyncPair
from app.paths import Layout
from app.services.files.scope import UPLOAD_TEMP_PREFIX
from app.services.offload.store import excluded_paths

_SPECIAL = re.compile(r"([\\*?\[\]{}])")
# Upload temp files (".drivesync-upload-<hex>", made beside the target when storage/ is on
# another disk) never sync. No leading "/": rclone then matches the name in every folder,
# the pair's own folder included (checked with real rclone; "- **/name" misses the root).
ALWAYS_EXCLUDED = ["- /.google-exports/**", f"- {UPLOAD_TEMP_PREFIX}*"]


_CONTROL = re.compile(r"[\x00-\x1f\x7f]")


def escape_filter_path(rel: str) -> str:
    if _CONTROL.search(rel):
        raise ValueError("path contains control characters")
    esc = _SPECIAL.sub(r"\\\1", rel)
    # rclone trims trailing whitespace from filter lines, and a backslash-escaped trailing
    # space is trimmed too (checked against real rclone); a character class survives.
    stripped = esc.rstrip()
    tail = esc[len(stripped) :]
    return stripped + "".join(f"[{c}]" for c in tail)


def render_filters(excluded: list[tuple[str, bool]]) -> str:
    lines = ["# Generated by DriveSync. Do not edit; changes are overwritten.", *ALWAYS_EXCLUDED]
    for path, is_dir in sorted(excluded):
        esc = escape_filter_path(path)
        lines.append(f"- /{esc}/**" if is_dir else f"- /{esc}")
    return "\n".join(lines) + "\n"


def write_filters(path: Path, content: str) -> bool:
    if path.exists() and path.read_text() == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(content)
    os.replace(tmp, path)
    return True


def pair_exclusions(db: Session, pair: SyncPair) -> list[tuple[str, bool]]:
    """Offloaded paths (spec §6.5): bisync must not see them on either side."""
    return list(excluded_paths(db, pair.id))


def refresh_pair_filters(db: Session, layout: Layout, pair: SyncPair) -> bool:
    return write_filters(layout.pair_filters(pair.id), render_filters(pair_exclusions(db, pair)))
